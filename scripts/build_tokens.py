"""Build the travel themes into every platform (SPEC-8 §15, D-237).

A travel theme is a package, ``design/themes/<id>/``: ``theme.json`` (its
light and dark semantic colours, effects, scene colours and tags) and
``scene.svg`` (the token-coloured scenery floor, D-239). This script is the one
place those packages become platform code, so a new theme is a new folder and
never a hand edit in four files:

- ``design/tokens/tokens.css``: the block between the travel-theme markers, one
  ``:root[data-travel="<id>"]`` rule set per mode. Base above the markers stays
  hand-kept (D-161, D-201).
- ``design/tokens/RundereThemes.swift`` and ``RundereThemes.kt``: palettes keyed
  by theme id, Base included, for the iOS and Android apps. They are looked up
  by id, never a closed enum, so the server can name a theme newer than the app.
- ``design/themes/<id>/scene-light.svg`` / ``scene-dark.svg``: fixed-colour
  scene exports for the iOS image sets and Android VectorDrawables.
- ``design/themes/themes.json``: the manifest the server validates
  ``users.ui_theme`` against and later serves at ``/api/v1/themes`` (D-240).

Usage::

    uv run python scripts/build_tokens.py           # write the outputs
    uv run python scripts/build_tokens.py --check   # exit 1 if any is stale

``tests/test_theme_packages.py`` runs ``--check`` and the contrast guardrails,
so a stale output or a failing theme fails CI.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens"
THEMES = ROOT / "design" / "themes"

# The 15 semantic roles every theme sets (design/README.md "Colour").
ROLES = (
    "bg", "surface", "surface-raised", "border", "border-subtle",
    "text", "text-secondary", "text-muted",
    "accent", "accent-hover", "on-accent",
    "highlight", "success", "danger", "focus-ring",
)
# The scenery floor's colours (D-239). Fills in scene.svg may use only these.
SCENE_ROLES = ("far", "mid", "near", "feature", "detail", "sun", "light", "star", "foam")
EFFECTS = ("shadow-raised", "glow-color")
MODES = ("light", "dark")
ID_RE = re.compile(r"^[a-z][a-z0-9-]{1,31}$")
# Ids the server keeps for itself: the base theme and the selection modes (D-240).
RESERVED = {"base", "random", "next-trip", "system"}

CSS_BEGIN = "/* ---- Travel themes (D-237). Generated by scripts/build_tokens.py from design/themes/; do not edit by hand. ---- */"
CSS_END = "/* ---- End of travel themes ---- */"
GENERATED = "Generated by scripts/build_tokens.py from design/tokens/tokens.json and design/themes/*/theme.json. Do not edit by hand."

SCENE_FILL = re.compile(r'style="(fill|stroke):var\(--rd-scene-([a-z]+)\)"')


class ThemeError(ValueError):
    pass


# ---------------------------------------------------------------- loading

def _resolve(value: str, colors: dict) -> str:
    """Resolve a tokens.json reference such as ``{color.night.900}``."""
    m = re.fullmatch(r"\{color\.([a-z]+)\.([a-z0-9-]+)\}", value)
    return colors[m.group(1)][m.group(2)]["$value"] if m else value


def load_base() -> dict:
    """Base's semantic colours, from the hand-kept tokens.json."""
    data = json.loads((TOKENS / "tokens.json").read_text())
    modes = {}
    for mode in MODES:
        sem = data["semantic"][mode]
        modes[mode] = {"color": {r: _resolve(sem[r]["$value"], data["color"]) for r in ROLES}}
    return {
        "id": "base", "name": "Base", "kind": "base", "version": 1, "tags": [],
        "description": "Night sky, silver and one beacon. The default for everyone.",
        "modes": modes,
    }


def load_theme(folder: Path) -> dict:
    """Read and validate one package. Raises ThemeError with the reason."""
    where = folder.name
    try:
        pkg = json.loads((folder / "theme.json").read_text())
    except (OSError, json.JSONDecodeError) as exc:
        raise ThemeError(f"{where}: unreadable theme.json ({exc})") from exc
    tid = pkg.get("id")
    if tid != folder.name:
        raise ThemeError(f"{where}: id {tid!r} must match its folder name")
    if not ID_RE.match(tid) or tid in RESERVED:
        raise ThemeError(f"{where}: id must be a lowercase slug and not one of {sorted(RESERVED)}")
    for key in ("name", "description"):
        if not isinstance(pkg.get(key), str) or not pkg[key].strip():
            raise ThemeError(f"{where}: {key} is required")
    if not isinstance(pkg.get("version"), int) or pkg["version"] < 1:
        raise ThemeError(f"{where}: version must be a positive integer")
    if not isinstance(pkg.get("tags"), list) or not all(isinstance(t, str) for t in pkg["tags"]):
        raise ThemeError(f"{where}: tags must be a list of strings")
    for mode in MODES:
        m = pkg.get("modes", {}).get(mode)
        if not isinstance(m, dict):
            raise ThemeError(f"{where}: missing the {mode} mode")
        for group, names in (("color", ROLES), ("effect", EFFECTS), ("scene", SCENE_ROLES)):
            got = m.get(group, {})
            if set(got) != set(names):
                raise ThemeError(f"{where}: {mode}.{group} must set exactly {list(names)}")
        for role in ROLES:
            if role != "border-subtle" and not _is_hex(m["color"][role]):
                raise ThemeError(f"{where}: {mode}.color.{role} must be #RRGGBB")
        for role in SCENE_ROLES:
            if not _is_hex(m["scene"][role]):
                raise ThemeError(f"{where}: {mode}.scene.{role} must be #RRGGBB")
    svg = (folder / pkg.get("scene", {}).get("file", "scene.svg"))
    if not svg.is_file():
        raise ThemeError(f"{where}: scene file {svg.name} is missing")
    text = svg.read_text()
    # Every colour in the scene must be a scene token, so it follows the theme
    # and the mode; a literal colour would break one of them.
    stray = re.findall(r'(?:fill|stroke)="(?!none")[^"]*"|#[0-9A-Fa-f]{3,6}\b|rgba?\(', text)
    if stray:
        raise ThemeError(f"{where}: scene.svg uses literal colours {stray[:3]}; use the rd-scene-* tokens")
    unknown = {r for _, r in SCENE_FILL.findall(text)} - set(SCENE_ROLES)
    if unknown:
        raise ThemeError(f"{where}: scene.svg uses unknown scene roles {sorted(unknown)}")
    pkg["kind"] = "travel"
    return pkg


def load_themes() -> list[dict]:
    return [load_theme(d) for d in sorted(p for p in THEMES.iterdir() if p.is_dir())]


def _is_hex(value: str) -> bool:
    return bool(re.fullmatch(r"#[0-9A-F]{6}", value or ""))


# ---------------------------------------------------------------- renderers

def render_css_block(themes: list[dict]) -> str:
    """One rule set per theme and mode. Dark is the default within a theme, as
    for Base; light follows the OS unless the page forces a mode (D-201)."""
    def decls(theme: dict, mode: str) -> str:
        m = theme["modes"][mode]
        lines = [f"  color-scheme: {mode};"]
        lines += [f"  --rd-{r}: {m['color'][r]};" for r in ROLES]
        lines.append(f"  --rd-shadow-raised: {m['effect']['shadow-raised']};")
        lines.append(f"  --rd-glow-color: {m['effect']['glow-color']};")
        lines.append(f"  --rd-glow: {'drop-shadow(0 0 14px ' + m['effect']['glow-color'] + ')' if mode == 'dark' else 'none'};")
        lines += [f"  --rd-scene-{r}: {m['scene'][r]};" for r in SCENE_ROLES]
        return "\n".join(lines)

    out = [CSS_BEGIN, ""]
    for t in themes:
        sel = f':root[data-travel="{t["id"]}"]'
        out += [
            f"/* {t['name']}: {t['description']} */",
            f"{sel} {{\n{decls(t, 'dark')}\n}}",
            f'@media (prefers-color-scheme: light) {{\n  {sel}:not([data-theme="dark"]) {{\n'
            + "\n".join("  " + ln for ln in decls(t, "light").splitlines()) + "\n  }\n}",
            f'{sel}[data-theme="light"] {{\n{decls(t, "light")}\n}}',
            "",
        ]
    out.append(CSS_END)
    return "\n".join(out)


def splice_css(current: str, block: str) -> str:
    if CSS_BEGIN in current:
        head, _, rest = current.partition(CSS_BEGIN)
        _, sep, tail = rest.partition(CSS_END)
        if not sep:
            raise ThemeError("tokens.css has the travel-theme start marker but no end marker")
        return head + block + tail
    return current.rstrip("\n") + "\n\n" + block + "\n"


def _camel(role: str) -> str:
    head, *rest = role.split("-")
    return head + "".join(p.capitalize() for p in rest)


def _argb(color: str) -> str:
    """#RRGGBB or rgba(r,g,b,a) as a Kotlin/Swift 0xAARRGGBB literal."""
    if color.startswith("#"):
        return "0xFF" + color[1:].upper()
    r, g, b, a = (float(x) for x in re.findall(r"[\d.]+", color))
    return "0x%02X%02X%02X%02X" % (round(a * 255), int(r), int(g), int(b))


def render_swift(all_themes: list[dict]) -> str:
    fields = "\n".join(f"    public let {_camel(r)}: Color" for r in ROLES)

    def palette(c: dict) -> str:
        args = ",\n".join(f"            {_camel(r)}: Color(argb: {_argb(c[r])})" for r in ROLES)
        return f"RDPalette(\n{args})"

    entries = "\n".join(
        f'        "{t["id"]}": RDThemePalettes(\n'
        f'            light: {palette(t["modes"]["light"]["color"])},\n'
        f'            dark: {palette(t["modes"]["dark"]["color"])}),'
        for t in all_themes
    )
    return f"""// Rundere theme palettes — SwiftUI. {GENERATED}
//
// Themes are looked up by id (D-237): the server may name a theme this build
// doesn't know, and `RDThemes.palettes(for:)` then falls back to Base. Inject the
// palette through the SwiftUI environment; RundereTheme.swift keeps Base's statics.

import SwiftUI

private extension Color {{
    init(argb: UInt32) {{
        self.init(.sRGB,
                  red: Double((argb >> 16) & 0xFF) / 255,
                  green: Double((argb >> 8) & 0xFF) / 255,
                  blue: Double(argb & 0xFF) / 255,
                  opacity: Double((argb >> 24) & 0xFF) / 255)
    }}
}}

public struct RDPalette {{
{fields}
}}

public struct RDThemePalettes {{
    public let light: RDPalette
    public let dark: RDPalette
}}

public enum RDThemes {{
    public static let all: [String: RDThemePalettes] = [
{entries}
    ]

    public static func palettes(for id: String) -> RDThemePalettes {{
        all[id] ?? all["base"]!
    }}
}}
"""


def _mix(a: str, b: str, t: float) -> str:
    pa, pb = _rgb(a), _rgb(b)
    return "#%02X%02X%02X" % tuple(round(pa[i] + (pb[i] - pa[i]) * t) for i in range(3))


def _rgb(h: str) -> tuple[int, int, int]:
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))  # type: ignore[return-value]


def material_roles(c: dict, dark: bool) -> dict:
    """Map a travel theme's semantic colours onto Material 3 roles. Base keeps
    its hand-tuned RundereDark / RundereLight schemes in RundereTheme.kt."""
    on_signal = c["bg"] if dark else c["surface"]
    return {
        "primary": c["accent"], "onPrimary": c["on-accent"],
        "primaryContainer": c["surface-raised"], "onPrimaryContainer": c["text"],
        "secondary": c["text-secondary"], "onSecondary": c["bg"] if dark else c["surface"],
        "secondaryContainer": c["border"], "onSecondaryContainer": c["text"],
        "tertiary": c["highlight"], "onTertiary": on_signal,
        "error": c["danger"], "onError": on_signal,
        "background": c["bg"], "onBackground": c["text"],
        "surface": c["bg"], "onSurface": c["text"], "onSurfaceVariant": c["text-secondary"],
        "surfaceContainerLowest": _mix(c["bg"], "#000000", 0.25) if dark else c["surface"],
        "surfaceContainerLow": _mix(c["bg"], c["surface"], 0.5) if dark else c["surface"],
        "surfaceContainer": c["surface"],
        "surfaceContainerHigh": c["surface-raised"] if dark else _mix(c["bg"], c["surface"], 0.5),
        "surfaceContainerHighest": c["border"] if dark else _mix(c["bg"], c["border"], 0.35),
        "outline": _mix(c["border"], c["text-muted"], 0.5), "outlineVariant": c["border"],
    }


def render_kotlin(travel: list[dict]) -> str:
    def scheme(t: dict, mode: str) -> str:
        fn = "darkColorScheme" if mode == "dark" else "lightColorScheme"
        roles = material_roles(t["modes"][mode]["color"], mode == "dark")
        body = "\n".join(f"        {k} = Color({_argb(v)})," for k, v in roles.items())
        return f"{fn}(\n{body}\n    )"

    entries = "\n".join(
        f'    "{t["id"]}" to RundereSchemes(\n'
        f'        light = {scheme(t, "light")},\n'
        f'        dark = {scheme(t, "dark")},\n'
        f"    ),"
        for t in travel
    )
    return f"""// Rundere theme colour schemes — Jetpack Compose Material 3. {GENERATED}
//
// Themes are looked up by id (D-237), never a closed enum: an id this build
// doesn't know falls back to Base. Base's schemes stay hand-tuned in RundereTheme.kt.

package app.rundere.ui.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

data class RundereSchemes(val light: ColorScheme, val dark: ColorScheme)

val RundereTravelSchemes: Map<String, RundereSchemes> = mapOf(
{entries}
)

fun rundereColorScheme(themeId: String, darkTheme: Boolean): ColorScheme {{
    val schemes = RundereTravelSchemes[themeId] ?: return if (darkTheme) RundereDark else RundereLight
    return if (darkTheme) schemes.dark else schemes.light
}}
"""


def render_scene(theme: dict, mode: str) -> str:
    text = (THEMES / theme["id"] / theme["scene"]["file"]).read_text()
    colors = theme["modes"][mode]["scene"]
    return SCENE_FILL.sub(lambda m: f'{m.group(1)}="{colors[m.group(2)]}"', text)


def render_manifest(all_themes: list[dict]) -> str:
    items = []
    for t in all_themes:
        item = {k: t[k] for k in ("id", "name", "kind", "version", "description", "tags")}
        item["modes"] = {
            mode: {k: v for k, v in t["modes"][mode].items() if k in ("color", "effect", "scene")}
            for mode in MODES
        }
        if t["kind"] == "travel":
            item["scene"] = {
                "title": t["scene"]["title"],
                "svg": f"{t['id']}/{t['scene']['file']}",
                "light": f"{t['id']}/scene-light.svg",
                "dark": f"{t['id']}/scene-dark.svg",
            }
        items.append(item)
    return json.dumps({"$description": GENERATED, "version": 1, "themes": items}, indent=2, ensure_ascii=False) + "\n"


# ---------------------------------------------------------------- driver

def outputs() -> dict[Path, str]:
    travel = load_themes()
    everything = [load_base()] + travel
    files = {
        TOKENS / "tokens.css": splice_css((TOKENS / "tokens.css").read_text(), render_css_block(travel)),
        TOKENS / "RundereThemes.swift": render_swift(everything),
        TOKENS / "RundereThemes.kt": render_kotlin(travel),
        THEMES / "themes.json": render_manifest(everything),
    }
    for t in travel:
        for mode in MODES:
            files[THEMES / t["id"] / f"scene-{mode}.svg"] = render_scene(t, mode)
    return files


def stale() -> list[Path]:
    return [p for p, text in outputs().items() if not p.is_file() or p.read_text() != text]


def main(argv: list[str]) -> int:
    try:
        if "--check" in argv:
            bad = stale()
            for p in bad:
                print(f"stale: {p.relative_to(ROOT)}")
            if bad:
                print("Run: uv run python scripts/build_tokens.py")
            return 1 if bad else 0
        for p, text in outputs().items():
            if not p.is_file() or p.read_text() != text:
                p.write_text(text)
                print(f"wrote {p.relative_to(ROOT)}")
        return 0
    except ThemeError as exc:
        print(f"theme error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
